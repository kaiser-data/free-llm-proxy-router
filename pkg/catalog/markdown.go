package catalog

import (
	"fmt"
	"io"
	"sort"
	"strings"
)

// WriteMarkdown renders the free entries of c as a human-readable Markdown
// page: a per-provider summary table followed by a collapsible model list
// for each provider.
func (c *Catalog) WriteMarkdown(w io.Writer) error {
	byProv := make(map[string][]CatalogEntry)
	for _, e := range c.FreeEntries() {
		byProv[e.ProviderID] = append(byProv[e.ProviderID], e)
	}
	provs := make([]string, 0, len(byProv))
	total := 0
	for p, es := range byProv {
		provs = append(provs, p)
		total += len(es)
		sort.Slice(es, func(i, j int) bool { return es[i].ModelID < es[j].ModelID })
	}
	// Most models first, then alphabetical.
	sort.Slice(provs, func(i, j int) bool {
		if len(byProv[provs[i]]) != len(byProv[provs[j]]) {
			return len(byProv[provs[i]]) > len(byProv[provs[j]])
		}
		return provs[i] < provs[j]
	})

	var b strings.Builder
	b.WriteString("# Free LLM models available today\n\n")
	b.WriteString("<!-- Generated by `free-llm-scan export-md` from configs/catalog.json. Do not edit by hand. -->\n\n")
	updated := "unknown"
	if !c.UpdatedAt.IsZero() {
		updated = c.UpdatedAt.UTC().Format("2006-01-02")
	}
	fmt.Fprintf(&b, "**%d free models** across **%d providers**, updated **%s**.\n\n", total, len(provs), updated)
	b.WriteString("Discovered automatically by scanning each provider's model API. ")
	b.WriteString("Use any of them through [free-llm-proxy-router](README.md) with a single OpenAI-compatible endpoint. ")
	b.WriteString("Free tiers change often, so check the provider's own terms before relying on one.\n\n")

	b.WriteString("| Provider | Free models | Largest context |\n|---|---:|---:|\n")
	for _, p := range provs {
		fmt.Fprintf(&b, "| [%s](#%s) | %d | %s |\n", p, p, len(byProv[p]), formatContext(maxContext(byProv[p])))
	}

	for _, p := range provs {
		fmt.Fprintf(&b, "\n## %s\n\n<details><summary>%d models</summary>\n\n| Model | Context |\n|---|---:|\n", p, len(byProv[p]))
		for _, e := range byProv[p] {
			fmt.Fprintf(&b, "| `%s` | %s |\n", e.ModelID, formatContext(e.ContextWindow))
		}
		b.WriteString("\n</details>\n")
	}

	_, err := io.WriteString(w, b.String())
	return err
}

func maxContext(es []CatalogEntry) int {
	m := 0
	for _, e := range es {
		if e.ContextWindow > m {
			m = e.ContextWindow
		}
	}
	return m
}

// formatContext prints token counts the way model cards do: powers of two as
// binary units (131072 → 128k, 1048576 → 1M), round decimals as-is (128000 → 128k).
func formatContext(n int) string {
	switch {
	case n <= 0:
		return "–"
	case n%(1<<20) == 0:
		return fmt.Sprintf("%dM", n>>20)
	case n >= 1_000_000:
		return strings.TrimSuffix(fmt.Sprintf("%.1f", float64(n)/1e6), ".0") + "M"
	case n%1000 == 0:
		return fmt.Sprintf("%dk", n/1000)
	case n%1024 == 0:
		return fmt.Sprintf("%dk", n>>10)
	case n >= 1000:
		return fmt.Sprintf("%dk", n/1000)
	default:
		return fmt.Sprintf("%d", n)
	}
}
